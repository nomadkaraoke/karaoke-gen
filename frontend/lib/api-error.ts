/** Error thrown for backend (and direct-to-GCS upload) failures. `status` 0 = network-level failure. */
export class ApiError extends Error {
  status: number;
  data?: any;

  constructor(message: string, status: number, data?: any) {
    super(message);
    this.name = 'ApiError';
    this.status = status;
    this.data = data;
  }
}
